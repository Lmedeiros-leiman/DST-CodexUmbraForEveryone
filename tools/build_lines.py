#!/usr/bin/env python3
"""Builds codex_everyone_lines.lua from the per-character JSON drafts.

Usage: python3 -I tools/build_lines.py <drafts dir> <output .lua> [<table .md>]

Each draft is {character, lines: {en, pt, zh, ru: {key: text}}, literal: {...}}.
Maxwell and Wortox have shadow_other and codex_banned (said when the host bans
them from shadow magic); everyone else has the five regular keys.
"""
import json
import sys
from pathlib import Path

LANGUAGES = ["en", "pt", "zh", "ru"]
KEYS = ["codex", "codex_needsfuel", "no_max_sanity", "shadow_mine", "shadow_other"]
PARTIAL = {"waxwell": ["shadow_other", "codex_banned"], "wortox": ["shadow_other", "codex_banned"]}
ORDER = ["wilson", "willow", "wolfgang", "wendy", "wx78", "wickerbottom", "woodie",
         "wathgrithr", "webber", "winona", "warly", "wormwood", "wurt", "walter",
         "wanda", "waxwell", "wortox"]
MAX_CHARS = 110  # a two-line speech bubble


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load(drafts):
    characters = {}
    problems = []
    for prefab in ORDER:
        path = drafts / f"{prefab}.json"
        if not path.exists():
            problems.append(f"{prefab}: missing draft")
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        keys = PARTIAL.get(prefab, KEYS)
        for lang in LANGUAGES:
            lines = data["lines"].get(lang, {})
            if sorted(lines) != sorted(keys):
                problems.append(f"{prefab}/{lang}: keys {sorted(lines)} != {sorted(keys)}")
            for key, text in lines.items():
                if not text.strip() or "\n" in text:
                    problems.append(f"{prefab}/{lang}/{key}: empty or multi-line")
                if len(text) > MAX_CHARS:
                    problems.append(f"{prefab}/{lang}/{key}: {len(text)} chars")
        characters[prefab] = data
    return characters, problems


def write_lua(characters, out):
    rows = ["-- Generated by tools/build_lines.py from the per-character drafts. Do not edit by hand.",
            "codex_everyone_lines =", "{",
            "    languages = { " + ", ".join(f"{l} = true" for l in LANGUAGES) + " },",
            "    characters =", "    {"]
    for prefab in ORDER:
        data = characters[prefab]
        rows.append(f"        {prefab} =")
        rows.append("        {")
        for lang in LANGUAGES:
            rows.append(f"            {lang} =")
            rows.append("            {")
            for key in PARTIAL.get(prefab, KEYS):
                rows.append(f"                {key} = {lua_string(data['lines'][lang][key])},")
            rows.append("            },")
        rows.append("        },")
    rows += ["    },", "}", ""]
    Path(out).write_text("\n".join(rows), encoding="utf-8")


def write_table(characters, out):
    names = {"wathgrithr": "Wigfrid", "wx78": "WX-78", "waxwell": "Maxwell"}
    md = ["# Codex Umbra for Everyone: character lines", "",
          "Literal English meanings of the translations are in brackets.", ""]
    for prefab in ORDER:
        data = characters[prefab]
        md.append(f"## {names.get(prefab, prefab.capitalize())}")
        md.append("")
        md.append("| Moment | English | Português | 简体中文 | Русский |")
        md.append("|---|---|---|---|---|")
        for key in PARTIAL.get(prefab, KEYS):
            cells = [data["lines"]["en"][key]]
            for lang in ["pt", "zh", "ru"]:
                lit = data.get("literal", {}).get(lang, {}).get(key, "")
                cells.append(data["lines"][lang][key] + (f" [{lit}]" if lit else ""))
            md.append(f"| `{key}` | " + " | ".join(c.replace("|", "\\|") for c in cells) + " |")
        md.append("")
    Path(out).write_text("\n".join(md), encoding="utf-8")


if __name__ == "__main__":
    drafts = Path(sys.argv[1])
    characters, problems = load(drafts)
    for p in problems:
        print("PROBLEM:", p)
    if problems:
        sys.exit(1)
    write_lua(characters, sys.argv[2])
    if len(sys.argv) > 3:
        write_table(characters, sys.argv[3])
    print(f"{len(characters)} characters, {sum(len(PARTIAL.get(p, KEYS)) for p in characters) * len(LANGUAGES)} lines")
